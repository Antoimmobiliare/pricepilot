do $$
declare
    next_id bigint;
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'properties'
          and column_name = 'id'
          and data_type in ('bigint', 'integer')
          and column_default is null
    ) then
        create sequence if not exists public.properties_legacy_id_seq;
        execute 'select coalesce(max(id), 0) + 1 from public.properties' into next_id;
        perform setval('public.properties_legacy_id_seq', greatest(next_id, 1), false);
        alter sequence public.properties_legacy_id_seq owned by public.properties.id;
        alter table public.properties
            alter column id set default nextval('public.properties_legacy_id_seq');
    end if;

    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'pricing_rules'
          and column_name = 'id'
          and data_type in ('bigint', 'integer')
          and column_default is null
    ) then
        create sequence if not exists public.pricing_rules_legacy_id_seq;
        execute 'select coalesce(max(id), 0) + 1 from public.pricing_rules' into next_id;
        perform setval('public.pricing_rules_legacy_id_seq', greatest(next_id, 1), false);
        alter sequence public.pricing_rules_legacy_id_seq owned by public.pricing_rules.id;
        alter table public.pricing_rules
            alter column id set default nextval('public.pricing_rules_legacy_id_seq');
    end if;
end $$;


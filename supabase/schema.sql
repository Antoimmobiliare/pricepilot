create or replace function private.is_account_member(p_account_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
    select exists (
        select 1
        from public.account_members m
        where m.account_id = p_account_id
          and m.user_id = auth.uid()
    );
$$;

create or replace function private.is_account_owner(p_account_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
    select exists (
        select 1
        from public.account_members m
        where m.account_id = p_account_id
          and m.user_id = auth.uid()
          and m.role = 'owner'
    );
$$;

create or replace function private.owns_account_record(p_account_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
    select exists (
        select 1
        from public.accounts a
        where a.id = p_account_id
          and a.owner_user_id = auth.uid()
    );
$$;


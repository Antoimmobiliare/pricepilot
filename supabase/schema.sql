-- PricePilot Supabase schema
-- Apply this file in the Supabase SQL editor before enabling real cloud sync.
--
-- Security model:
-- - Supabase Auth owns user identity.
-- - public.account_members maps auth.users.id to a PricePilot account.
-- - Every tenant table is protected by RLS through account_id.
-- - No anon policy is granted for customer data.

create extension if not exists pgcrypto;

create schema if not exists private;
revoke all on schema private from public;
revoke all on schema private from anon;
revoke all on schema private from authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text not null default '',
    full_name text not null default '',
